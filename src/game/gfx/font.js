/** Titre d'impact : sx/sy = étirement, lean = pente de l'italique (pixels par rangée). */
export function drawBig(ctx, s, x, y, { color = "#fff", sx = 1, sy = 2, outline = "#140c1c", lean = 0.25, ow = 1 } = {}) {
  s = clean(s);
  const x0 = Math.round(x - bigWidth(s, sx) / 2), y0 = Math.round(y), H = 7 * sy;
  const pass = (dx, dy, col) => {
    ctx.fillStyle = col;
    [...s].forEach((ch, i) => {
      const g = B[ch];
      if (!g) return;
      for (let k = 0; k < 35; k++) if (g[k] === "1") {
        const row = (k / 5) | 0;
        const sh = Math.round((H - row * sy) * lean);
        ctx.fillRect(x0 + i * 6 * sx + (k % 5) * sx + sh + dx, y0 + row * sy + dy, sx, sy);
      }
    });
  };
  if (outline) for (let dx = -ow; dx <= ow; dx++) for (let dy = -ow; dy <= ow; dy++) if (dx || dy) pass(dx, dy, outline);
  pass(0, 0, color);
}
